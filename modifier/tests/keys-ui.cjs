// 鑰匙：修改器「鑰匙」頁的數量增減（Electron，離線夾具）
const { app, BrowserWindow } = require('electron');
const fs = require('node:fs'), path = require('node:path'), os = require('node:os'), assert = require('node:assert/strict');
const temp = fs.mkdtempSync(path.join(os.tmpdir(), 'd2-keys-ui-'));
app.setPath('userData', path.join(temp, 'profile'));
const preload = path.join(temp, 'preload.cjs');
fs.writeFileSync(preload, `window.api={web:false,assets:async()=>({dir:'',uniques:{},sets:{},bases:{},quest:{},runes:{},gems:{}}),i18n:async()=>({dict:{},game:{stats:{},classes:{}}}),load:async()=>({save:{version:6,gold:1,stashTabs:{},equippedByClass:{},unlocked:{}},source:'fixture'}),engine:async()=>null};`);
const watchdog = setTimeout(() => { console.error('鑰匙介面測試逾時'); app.exit(1); }, 30000);
app.whenReady().then(async () => {
  const win = new BrowserWindow({ show: false, webPreferences: { preload, contextIsolation: false, nodeIntegration: false } });
  await win.loadFile(path.join(__dirname, '..', 'editor.html'));
  const r = await win.webContents.executeJavaScript(`(async()=>{
    const out = {};
    save.pandemonium = { mbr: ['brain-1'] };
    cur = 'keys'; renderView();
    const inp = (c) => document.querySelector('[data-key="' + c + '"]');
    out.initial = { pk1: inp('pk1').value, pk2: inp('pk2').value, pk3: inp('pk3').value };
    out.hasContainer = !!contById('keys');
    inp('pk1').value = '2'; inp('pk1').dispatchEvent(new Event('change'));
    out.pk1 = save.pandemonium.pk1.slice();
    out.mbrKept = save.pandemonium.mbr.slice();
    inp('pk2').value = '1'; inp('pk2').dispatchEvent(new Event('change'));
    out.pk2 = save.pandemonium.pk2.length;
    inp('pk1').value = '1'; inp('pk1').dispatchEvent(new Event('change'));
    out.pk1Trim = save.pandemonium.pk1.length; out.pk1KeptFirst = save.pandemonium.pk1[0] === out.pk1[0];
    inp('pk2').value = '0'; inp('pk2').dispatchEvent(new Event('change'));
    out.pk2Removed = !('pk2' in save.pandemonium);
    inp('pk3').value = '1000'; inp('pk3').dispatchEvent(new Event('change'));
    out.pk3Clamped = save.pandemonium.pk3.length; out.pk3ShownAs = inp('pk3').value;
    inp('pk3').value = '-5'; inp('pk3').dispatchEvent(new Event('change'));
    out.pk3Neg = save.pandemonium.pk3 === undefined ? 'removed' : save.pandemonium.pk3.length;
    document.querySelector('#keys-one').click();
    out.allOne = [save.pandemonium.pk1.length, save.pandemonium.pk2.length, save.pandemonium.pk3.length];
    out.idsValid = [...save.pandemonium.pk1, ...save.pandemonium.pk2, ...save.pandemonium.pk3].every(s => /^[\\w-]{1,32}$/.test(s));
    out.idsUnique = new Set([save.pandemonium.pk1[0], save.pandemonium.pk2[0], save.pandemonium.pk3[0]]).size === 3;
    out.organsKept = save.pandemonium.mbr.length;
    document.querySelector('#organs-one').click();
    out.organsOne = [save.pandemonium.mbr.length, save.pandemonium.dhn.length, save.pandemonium.bey.length];
    out.keysAfterOrgans = [save.pandemonium.pk1.length, save.pandemonium.pk2.length, save.pandemonium.pk3.length];
    inp('dhn').value = '2'; inp('dhn').dispatchEvent(new Event('change'));
    out.dhn = save.pandemonium.dhn.length;
    inp('bey').value = '0'; inp('bey').dispatchEvent(new Event('change'));
    out.beyRemoved = !('bey' in save.pandemonium);
    out.keysKeptAfterOrganEdit = save.pandemonium.pk1.length === 1;
    return out;
  })()`);
  assert.deepEqual(r.initial, { pk1: '0', pk2: '0', pk3: '0' });
  assert.equal(r.hasContainer, true);
  assert.equal(r.pk1.length, 2); assert.equal(r.pk2, 1);
  assert.deepEqual(r.mbrKept, ['brain-1']);
  assert.equal(r.pk1Trim, 1); assert.equal(r.pk1KeptFirst, true);
  assert.equal(r.pk2Removed, true);
  assert.equal(r.pk3Clamped, 999); assert.equal(r.pk3ShownAs, '999');
  assert.equal(r.pk3Neg, 'removed');
  assert.deepEqual(r.allOne, [1, 1, 1]);
  assert.equal(r.idsValid, true); assert.equal(r.idsUnique, true);
  assert.equal(r.organsKept, 1);
  assert.deepEqual(r.organsOne, [1, 1, 1]); assert.deepEqual(r.keysAfterOrgans, [1, 1, 1]);
  assert.equal(r.dhn, 2); assert.equal(r.beyRemoved, true); assert.equal(r.keysKeptAfterOrganEdit, true);
  console.log('鑰匙介面測試通過'); clearTimeout(watchdog); app.exit(0);
}).catch(e => { console.error(e.stack); clearTimeout(watchdog); app.exit(1); });
